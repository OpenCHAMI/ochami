//go:build unix

package config

import (
	"os"
	"syscall"
)

// fileOwner returns the user and group IDs that own the file fi describes, or
// false if fi doesn't report them.
func fileOwner(fi os.FileInfo) (uid, gid int, ok bool) {
	st, ok := fi.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, 0, false
	}
	return int(st.Uid), int(st.Gid), true
}
